#!/usr/bin/env node
// Reads admob.config.json, then:
//   1. writes www/ads-config.js (the ad unit IDs the game uses)
//   2. writes the AdMob App ID into the Android project (strings.xml)
// Run it before every build: node scripts/apply-admob.js
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const TEST_PUBLISHER = 'ca-app-pub-3940256099942544'; // Google's test publisher

function fail(msg) {
  console.error('\nERROR: ' + msg + '\n');
  process.exit(1);
}

let cfg;
try {
  cfg = JSON.parse(fs.readFileSync(path.join(root, 'admob.config.json'), 'utf8'));
} catch (e) {
  fail('Could not read admob.config.json: ' + e.message);
}

if (!/^ca-app-pub-\d+~\d+$/.test(cfg.appId || '')) {
  fail('"appId" must look like ca-app-pub-1234567890123456~1234567890 (note the ~ sign).');
}
for (const k of ['banner', 'interstitial', 'rewarded']) {
  if (!/^ca-app-pub-\d+\/\d+$/.test(cfg[k] || '')) {
    fail('"' + k + '" must look like ca-app-pub-1234567890123456/1234567890 (note the / sign).');
  }
}

const all = [cfg.appId, cfg.banner, cfg.interstitial, cfg.rewarded];
const testCount = all.filter(v => v.startsWith(TEST_PUBLISHER)).length;
if (testCount !== 0 && testCount !== all.length) {
  fail('Mixed IDs: some are Google test IDs and some are yours. Use all test IDs or all of your own.');
}
const usingTest = testCount === all.length;

const adsConfig = {
  testing: usingTest,
  banner: cfg.banner,
  interstitial: cfg.interstitial,
  rewarded: cfg.rewarded
};
fs.writeFileSync(
  path.join(root, 'www', 'ads-config.js'),
  '// Generated by scripts/apply-admob.js from admob.config.json. Do not edit by hand.\n' +
    'window.ADS_CONFIG = ' + JSON.stringify(adsConfig, null, 2) + ';\n'
);

const stringsPath = path.join(root, 'android', 'app', 'src', 'main', 'res', 'values', 'strings.xml');
if (fs.existsSync(stringsPath)) {
  let xml = fs.readFileSync(stringsPath, 'utf8');
  const tag = '<string name="admob_app_id">' + cfg.appId + '</string>';
  const existing = /<string name="admob_app_id">[^<]*<\/string>/;
  xml = existing.test(xml) ? xml.replace(existing, tag) : xml.replace('</resources>', '    ' + tag + '\n</resources>');
  fs.writeFileSync(stringsPath, xml);
} else {
  console.warn('Android project not found. Run: npx cap add android');
}

console.log(usingTest
  ? 'AdMob: using Google TEST ads (safe to tap). Add your own IDs to admob.config.json before publishing.'
  : 'AdMob: using YOUR real ad IDs. Never tap your own ads, as this can get your AdMob account banned.');
